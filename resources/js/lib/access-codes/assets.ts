export const PS_SCRIPT = `#Requires -Version 5.1
<#
.SYNOPSIS
    Setzt Passwörter für Schüler-Konten in Microsoft 365 anhand der CSV-Datei
    aus dem Zugangsdaten-Generator ("zugangsdaten.csv").

.DESCRIPTION
    Liest eine CSV mit den Spalten Nachname;Vorname;Benutzername;Passwort;PIN ein
    und setzt für jeden Benutzernamen (UPN) das dazugehörige Passwort über
    Microsoft Graph. Der PIN wird NICHT hochgeladen (er ist nur zur eigenen
    Dokumentation/Verteilung an die Schüler gedacht).

.PARAMETER CsvPath
    Pfad zur CSV-Datei aus dem Generator. Standard: .\\zugangsdaten.csv

.PARAMETER ForceChangeAtNextLogin
    Wenn gesetzt (Standard: $false), müssen Schüler das Passwort NICHT beim
    nächsten Login ändern. Auf $true setzen, falls eine Änderung beim ersten
    Login doch erzwungen werden soll.

.PARAMETER WhatIf
    Führt einen Testlauf aus, ohne tatsächlich Passwörter zu setzen. Zeigt nur,
    was passieren würde. Empfohlen für den ersten Durchlauf.

.EXAMPLE
    .\\Set-O365Passwords.ps1 -CsvPath .\\zugangsdaten.csv -WhatIf

.EXAMPLE
    .\\Set-O365Passwords.ps1 -CsvPath .\\zugangsdaten.csv -ForceChangeAtNextLogin:$true

.NOTES
    Benötigt das Modul Microsoft.Graph (Users) und eine Rolle mit Berechtigung
    zum Zurücksetzen von Passwörtern (z. B. "User Administrator" oder
    "Global Administrator") sowie den Scope "User.ReadWrite.All".

    Das Skript setzt PasswordPolicies auf "None", damit das reguläre
    Passwort-Ablaufdatum des Tenants für diese Konten aktiv ist/bleibt
    (keine Ausnahme "DisablePasswordExpiration").
#>

[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [Parameter(Mandatory = $false)]
    [string]$CsvPath = ".\\zugangsdaten.csv",

    [Parameter(Mandatory = $false)]
    [bool]$ForceChangeAtNextLogin = $false,

    [Parameter(Mandatory = $false)]
    [string]$LogPath = ".\\zugangsdaten-import-log.csv"
)

# --- Vorbereitung -----------------------------------------------------------

if (-not (Test-Path $CsvPath)) {
    Write-Error "CSV-Datei nicht gefunden: $CsvPath"
    return
}

# Microsoft.Graph.Users Modul sicherstellen
if (-not (Get-Module -ListAvailable -Name Microsoft.Graph.Users)) {
    Write-Host "Modul 'Microsoft.Graph.Users' wird installiert (einmalig)..." -ForegroundColor Yellow
    Install-Module Microsoft.Graph.Users -Scope CurrentUser -Force -AllowClobber
}

Import-Module Microsoft.Graph.Users

# Verbindung zu Microsoft Graph herstellen
Write-Host "Verbinde mit Microsoft Graph..." -ForegroundColor Cyan
Connect-MgGraph -Scopes "User.ReadWrite.All" -NoWelcome

# --- CSV einlesen ------------------------------------------------------------
# Export aus dem Generator ist UTF-8 mit BOM und Semikolon-getrennt
$rows = Import-Csv -Path $CsvPath -Delimiter ';' -Encoding UTF8

if ($rows.Count -eq 0) {
    Write-Warning "Die CSV-Datei enthält keine Zeilen."
    return
}

Write-Host "Gefunden: $($rows.Count) Schüler-Einträge in $CsvPath" -ForegroundColor Cyan

$results = @()

foreach ($row in $rows) {

    $upn = $row.Benutzername
    $pw  = $row.Passwort

    if ([string]::IsNullOrWhiteSpace($upn)) {
        Write-Warning "Zeile ohne Benutzername übersprungen: $($row.Nachname) $($row.Vorname)"
        $results += [PSCustomObject]@{
            Benutzername = ""
            Nachname     = $row.Nachname
            Vorname      = $row.Vorname
            Status       = "Übersprungen (kein Benutzername)"
        }
        continue
    }

    if ([string]::IsNullOrWhiteSpace($pw)) {
        Write-Warning "Zeile ohne Passwort übersprungen: $upn"
        $results += [PSCustomObject]@{
            Benutzername = $upn
            Nachname     = $row.Nachname
            Vorname      = $row.Vorname
            Status       = "Übersprungen (kein Passwort)"
        }
        continue
    }

    $passwordProfile = @{
        Password                      = $pw
        ForceChangePasswordNextSignIn = $ForceChangeAtNextLogin
    }

    if ($PSCmdlet.ShouldProcess($upn, "Passwort setzen")) {
        try {
            Update-MgUser -UserId $upn -PasswordProfile $passwordProfile -PasswordPolicies "None" -ErrorAction Stop
            Write-Host "OK: $upn" -ForegroundColor Green
            $results += [PSCustomObject]@{
                Benutzername = $upn
                Nachname     = $row.Nachname
                Vorname      = $row.Vorname
                Status       = "Erfolgreich gesetzt"
            }
        }
        catch {
            Write-Host "FEHLER bei \${upn}: $($_.Exception.Message)" -ForegroundColor Red
            $results += [PSCustomObject]@{
                Benutzername = $upn
                Nachname     = $row.Nachname
                Vorname      = $row.Vorname
                Status       = "Fehler: $($_.Exception.Message)"
            }
        }
    }
    else {
        # -WhatIf Modus
        $results += [PSCustomObject]@{
            Benutzername = $upn
            Nachname     = $row.Nachname
            Vorname      = $row.Vorname
            Status       = "Testlauf (nicht ausgeführt)"
        }
    }
}

# --- Zusammenfassung ---------------------------------------------------------

$results | Export-Csv -Path $LogPath -Delimiter ';' -NoTypeInformation -Encoding UTF8

$success = ($results | Where-Object { $_.Status -eq "Erfolgreich gesetzt" }).Count
$failed  = ($results | Where-Object { $_.Status -like "Fehler:*" }).Count
$skipped = ($results | Where-Object { $_.Status -like "Übersprungen*" }).Count

Write-Host ""
Write-Host "-------------------------------------------" -ForegroundColor Cyan
Write-Host "Fertig: $success erfolgreich, $failed fehlgeschlagen, $skipped übersprungen." -ForegroundColor Cyan
Write-Host "Detailliertes Log gespeichert unter: $LogPath" -ForegroundColor Cyan
Write-Host "-------------------------------------------" -ForegroundColor Cyan

Disconnect-MgGraph | Out-Null
`;
